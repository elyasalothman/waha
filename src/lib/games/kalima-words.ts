function unique(list: string[]): string[] {
  return [...new Set(list)];
}

export const AR_OK = new Set(unique([...AR_ANSWERS, ...AR_EXTRA]));
export const EN_OK = new Set(unique([...EN_ANSWERS, ...EN_EXTRA]));

export function pickAnswer(mode: "ar" | "en", daily: boolean, salt = 0): string {
  const pool = mode === "ar" ? AR_ANSWERS : EN_ANSWERS;
  if (daily) {
    const rng = mulberry32(daySeed() + salt + (mode === "ar" ? 17 : 41));
    return pool[Math.floor(rng() * pool.length)]!;
  }
  return pool[Math.floor(Math.random() * pool.length)]!;
}

export function isAllowed(mode: "ar" | "en", word: string): boolean {
  return mode === "ar" ? AR_OK.has(word) : EN_OK.has(word);
}
